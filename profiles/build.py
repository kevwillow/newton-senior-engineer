import argparse
import sys
import tomllib
from pathlib import Path

TIER_ORDER = ("standard", "hardened", "lockdown")
TIER_SETS = {
    "standard": ("standard",),
    "hardened": ("standard", "hardened"),
    "lockdown": ("standard", "hardened", "lockdown"),
}
REQUIRED_KEYS = (
    "id",
    "tier",
    "title",
    "lab",
    "scenario",
    "step_up_of",
    "form_of",
    "preconditions",
    "batch",
    "check",
    "expect",
    "check_host",
    "check_from",
    "check_kind",
    "lab_bound",
    "notes",
)
INCLUDED_LABS = ("proven", "caveat")
HEADER = "# GENERATED by profiles/build.py from manifest.toml: do not edit"


class BuildError(Exception):
    pass


def default_manifest():
    return Path(__file__).resolve().parent / "openwrt" / "manifest.toml"


def load_manifest(path):
    path = Path(path)
    if not path.is_file():
        raise BuildError(f"manifest not found: {path}")
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        raise BuildError(f"manifest is not valid TOML: {path}: {exc}") from None
    controls = data.get("control", [])
    if not isinstance(controls, list):
        raise BuildError(f"manifest {path}: [[control]] is not a list of tables")
    for pos, entry in enumerate(controls, 1):
        if not isinstance(entry, dict):
            raise BuildError(f"manifest {path}: control entry {pos} is not a table")
        missing = [key for key in REQUIRED_KEYS if key not in entry]
        if missing:
            label = entry.get("id", f"entry {pos}")
            raise BuildError(
                f"manifest {path}: control {label} lacks key(s): {', '.join(missing)}"
            )
    return controls


def entry_included(entry, tiers):
    return (
        entry["tier"] in tiers
        and entry["form_of"] == ""
        and entry["lab"] in INCLUDED_LABS
    )


def select_controls(controls, tier):
    tiers = TIER_SETS[tier]
    selected = []
    index = {}
    for entry in controls:
        if not entry_included(entry, tiers):
            continue
        if entry["step_up_of"] != "" and entry["id"] in index:
            selected[index[entry["id"]]] = entry
            continue
        if entry["id"] not in index:
            index[entry["id"]] = len(selected)
            selected.append(entry)
    return selected


def package_preconditions(entry):
    return [item.removeprefix("package ") for item in entry["preconditions"]
            if item.startswith("package ")]


def conditional(entry):
    return bool(entry["batch"] and package_preconditions(entry))


def batch_options(entry):
    options = []
    for line in entry["batch"]:
        words = line.split(None, 1)
        if len(words) != 2 or words[0] not in ("set", "add_list"):
            continue
        options.append(words[1].split("=", 1)[0])
    return options


def render_uci(tier, entries, controls):
    lab_ids = [entry["id"] for entry in entries
               if entry["batch"] and "batch" in entry["lab_bound"]
               and not conditional(entry)]
    conditional_items = [
        f"{entry['id']} ({', '.join(package_preconditions(entry))})"
        for entry in entries if conditional(entry)
    ]
    lines = [
        HEADER,
        f"# tier: {tier}",
        "# lab-bound batches (lab-r1 names, not portable): "
        + (", ".join(lab_ids) or "none"),
        "# conditional batches (commented out below, need a package): "
        + (", ".join(conditional_items) or "none"),
    ]
    for entry in entries:
        lines.append("")
        lines.append(f"# {entry['id']} {entry['title']}")
        if entry["step_up_of"]:
            base = next(control for control in controls
                        if control["id"] == entry["id"]
                        and control["tier"] == entry["step_up_of"])
            current_options = set(batch_options(entry))
            replaced = [option for option in batch_options(base)
                        if option not in current_options]
            lines.append(
                f"# step-up from {entry['step_up_of']}: replaces "
                f"{', '.join(replaced)}. If {entry['step_up_of']} is already "
                "applied, delete those first; this file cannot, because uci "
                "batch rejects a delete of a missing option."
            )
        if (entry["batch"] and "batch" in entry["lab_bound"]
                and not conditional(entry)):
            lines.append("# lab-bound: names an interface, zone or address "
                         "that exists only on lab-r1")
        if conditional(entry):
            packages = ", ".join(package_preconditions(entry))
            lines.append(f"# conditional: needs package {packages}; "
                         "not applied by this file")
            lines.extend(f"# {line}" for line in entry["batch"])
        elif entry["batch"]:
            lines.extend(entry["batch"])
        else:
            other = next((candidate for candidate in entries
                          if candidate is not entry
                          and candidate["scenario"] == entry["scenario"]
                          and entry["scenario"]
                          and candidate["batch"]), None)
            if other:
                lines.append("# no lines of its own: the change is in "
                             f"{other['id']} (same scenario)")
            else:
                lines.append("# no lines of its own")
    return "\n".join(lines) + "\n"


def build_files(manifest_path, out_dir):
    controls = load_manifest(manifest_path)
    out_dir = Path(out_dir)
    written = []
    for tier in TIER_ORDER:
        text = render_uci(tier, select_controls(controls, tier), controls)
        target = out_dir / f"{tier}.uci"
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def parse_args(argv):
    manifest = default_manifest()
    parser = argparse.ArgumentParser(
        description="Generate the OpenWrt tier .uci profiles from the manifest"
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=manifest,
        help=f"path to manifest.toml (default: {manifest})",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=None,
        help="directory for the .uci files (default: the manifest's directory)",
    )
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    out_dir = args.out_dir
    if out_dir is None:
        out_dir = args.manifest.resolve().parent
    try:
        written = build_files(args.manifest, out_dir)
    except BuildError as exc:
        print(f"build.py: error: {exc}", file=sys.stderr)
        return 1
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
