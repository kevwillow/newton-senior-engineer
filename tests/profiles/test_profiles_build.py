"""Tests for profiles/build.py."""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROFILES = ROOT / "profiles"
OPENWRT = PROFILES / "openwrt"
TIERS = ("standard", "hardened", "lockdown")
HEADER = "# GENERATED by profiles/build.py from manifest.toml: do not edit"


def run_build(out_dir, manifest=None):
    argv = [sys.executable, str(PROFILES / "build.py"), "--out-dir", str(out_dir)]
    if manifest is not None:
        argv += ["--manifest", str(manifest)]
    return subprocess.run(argv, capture_output=True, text=True)


def build_into(tmp_path, name):
    out = tmp_path / name
    out.mkdir()
    result = run_build(out)
    assert result.returncode == 0, result.stderr
    return out


def test_build_is_deterministic(tmp_path):
    a = build_into(tmp_path, "a")
    b = build_into(tmp_path, "b")
    for tier in TIERS:
        assert (a / f"{tier}.uci").read_bytes() == (b / f"{tier}.uci").read_bytes()


def test_checked_in_uci_files_equal_a_fresh_build(tmp_path):
    out = build_into(tmp_path, "uci")
    for tier in TIERS:
        fresh = (out / f"{tier}.uci").read_bytes()
        assert fresh == (OPENWRT / f"{tier}.uci").read_bytes(), tier


def test_line_1_of_every_uci_is_the_header(tmp_path):
    out = build_into(tmp_path, "uci")
    for tier in TIERS:
        first = (out / f"{tier}.uci").read_text().splitlines()[0]
        assert first == HEADER, tier


def test_lockdown_has_directinterface_and_no_interface_line(tmp_path):
    out = build_into(tmp_path, "uci")
    text = (out / "lockdown.uci").read_text()
    assert "DirectInterface" in text
    offenders = [line for line in text.splitlines() if ".Interface=" in line]
    assert offenders == []


def block_ids(text):
    return [line.split()[1] for line in text.splitlines()
            if line.startswith("# OW-")]


def test_blocks_are_cumulative_up_the_tiers(tmp_path):
    out = build_into(tmp_path, "uci")
    std = set(block_ids((out / "standard.uci").read_text()))
    hard = set(block_ids((out / "hardened.uci").read_text()))
    lock = set(block_ids((out / "lockdown.uci").read_text()))
    assert (std - {"OW-MGMT-01"}) <= hard
    assert (hard - {"OW-MGMT-01"}) <= lock


def test_excluded_controls_appear_in_no_uci_file(tmp_path):
    out = build_into(tmp_path, "uci")
    forbidden = ("OW-MGMT-06", "OW-ZONE-03", "OW-WIFI-02",
                 "OW-MGMT-04", "OW-ZONE-01")
    for tier in TIERS:
        text = (out / f"{tier}.uci").read_text()
        for ctl in forbidden:
            assert ctl not in text, (tier, ctl)


def test_missing_manifest_exit_1_one_stderr_line_no_traceback(tmp_path):
    out = tmp_path / "out"
    out.mkdir()
    result = run_build(out, manifest=tmp_path / "no-such-manifest.toml")
    assert result.returncode == 1
    assert "Traceback" not in result.stderr
    lines = [line for line in result.stderr.splitlines() if line.strip()]
    assert len(lines) == 1
    assert "manifest not found" in lines[0]


# What `scripts/owrt-safe-apply.sh stage` lets through (its verb filter): blank lines, lines whose first non-space
# character is #, and lines that start with one of these verbs. The whole file, comments included, then goes to
# `uci batch`, so a comment line must not carry a quote that could swallow the lines after it.
STAGE_VERBS = ("set", "add", "add_list", "del_list", "delete", "rename", "reorder")
STAGE_VERB_RE = re.compile(r"^[ \t]*(" + "|".join(STAGE_VERBS) + r")[ \t]")
COMMENTED_BATCH_RE = re.compile(r"^# (" + "|".join(STAGE_VERBS) + r") ")


def stage_problems(text):
    problems = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        if line.lstrip().startswith("#"):
            quoted = "'" in line or '"' in line
            if quoted and not COMMENTED_BATCH_RE.match(line):
                problems.append(f"line {number}: quote character in a comment line: {line}")
            elif quoted and (line.count("'") % 2 or line.count('"') % 2):
                problems.append(f"line {number}: unbalanced quote in a commented-out batch line: {line}")
        elif not STAGE_VERB_RE.match(line):
            problems.append(f"line {number}: stage would refuse this line: {line}")
    return problems


def test_tier_files_can_be_staged_as_text():
    for tier in TIERS:
        text = (OPENWRT / f"{tier}.uci").read_text(encoding="utf-8")
        assert stage_problems(text) == [], tier


def test_stage_problems_sees_a_refused_verb_and_a_bad_quote():
    text = "set a.b.c='1'\ncommit a\n# it's\n# set a.b.c='1\n# set a.b.c='1'\n\n"
    assert stage_problems(text) == [
        "line 2: stage would refuse this line: commit a",
        "line 3: quote character in a comment line: # it's",
        "line 4: unbalanced quote in a commented-out batch line: # set a.b.c='1",
    ]


def test_a_quote_in_a_title_reaches_a_comment_line_and_is_seen(tmp_path):
    text = (OPENWRT / "manifest.toml").read_text(encoding="utf-8")
    old = "title = 'SSH on LAN only'"
    assert text.count(old) == 1
    manifest = tmp_path / "manifest.toml"
    manifest.write_text(text.replace(old, 'title = "SSH on LAN\'s only"'), encoding="utf-8")
    out = tmp_path / "out"
    out.mkdir()
    result = run_build(out, manifest=manifest)
    assert result.returncode == 0, result.stderr
    problems = stage_problems((out / "standard.uci").read_text(encoding="utf-8"))
    assert any("quote character in a comment line" in line and "SSH on LAN's only" in line
               for line in problems), problems
