# SUP-08: `record` reads a runner results file (names and counts only) and appends a run once.
def _results(tmp_path, ok=("01-static-lease", "p-02-mgmt-ip-lockout"), bad=()):
    scenarios = [{"name": n, "passed": True, "vars": {"ip": "10.9.9.9"}} for n in ok]
    scenarios += [{"name": n, "passed": False} for n in bad]
    scenarios.append({"name": "ow-unrelated", "passed": True})
    path = tmp_path / "results.json"
    path.write_text(json.dumps({"timestamp": "2026-10-24T12:00:00-0400", "summary": "x", "scenarios": scenarios}))
    return path


def test_sup08_record_appends_run(data, tmp_path):
    results = _results(tmp_path, bad=("02-mgmt-ip-lockout",))
    st.record(
        data / "platforms.toml", data / "runs.toml", results,
        platform="openwrt", version="25.12.5", target="hardware: Asus RT-AX57M", kind="hardware",
        scenario_names=_scenario_names(),
    )
    platforms, runs = _load(data)
    new = runs[-1]
    assert new["date"] == "2026-10-24"
    assert new["results_sha256"] == hashlib.sha256(results.read_bytes()).hexdigest()
    assert sorted(new["shapes_passed"]) == ["01-static-lease", "p-02-mgmt-ip-lockout"]
    assert new["shapes_failed"] == ["02-mgmt-ip-lockout"]
    assert new["scenarios_passed"] == 3 and new["scenarios_failed"] == 1
    assert "10.9.9.9" not in (data / "runs.toml").read_text()
    with pytest.raises(st.SupportError, match="already recorded"):
        st.record(
            data / "platforms.toml", data / "runs.toml", results,
            platform="openwrt", version="25.12.5", target="hardware: Asus RT-AX57M", kind="hardware",
            scenario_names=_scenario_names(),
        )


