# SUP-18: the access mode of a run comes from the results, not from a
# flag (review item 3: the access mode was an operator assertion, not
# evidence detected by the recorded run).

def _results_with_access(tmp_path, access=None, name="results.json"):
    """A runner results file, with the access evidence the runner writes:
    the mode every scenario of the run exercised, the run's own fact
    and the device facts.  `access=None` writes a file with no access
    evidence at all."""
    scenarios = [{"name": n, "passed": True}
                 for n in ("01-static-lease", "02-mgmt-ip-lockout")]
    payload = {"timestamp": "2026-10-24T12:00:00-0400", "summary": "x",
               "scenarios": scenarios}
    if access is not None:
        payload["access"] = access
        payload["devices"] = [{"name": "lab-r1", "access": access}]
        for scenario in scenarios:
            scenario["access"] = access
    path = tmp_path / name
    path.write_text(json.dumps(payload))
    return path


def _results_with_payload(tmp_path, payload, name="results.json"):
    """A runner results file with an exact payload."""
    path = tmp_path / name
    path.write_text(json.dumps(payload))
    return path


def test_sup18_the_access_mode_comes_from_the_results(modes_data, tmp_path):
    """The results carry the mode the run was made in: the recorded run
    takes it from there, with no flag."""
    results = _results_with_access(tmp_path, access="no-install")
    st.record(
        modes_data / "platforms.toml", modes_data / "runs.toml", results,
        platform="openwrt", version="25.12.5", target="virtual image",
        kind="virtual", scenario_names=_scenario_names(),
    )
    _platforms, runs = _load(modes_data)
    assert runs[-1]["access"] == "no-install"


